import type { PantryCategory } from "@/types";

/**
 * The single canonical ingredient registry — the shared identity layer
 * behind Pantry, Shopping, and Discover.
 *
 * Every recipe ingredient, pantry item, and shopping item resolves to one
 * of these entries. `id` is the stable identity key (recipes already
 * reference it directly via `RecipeIngredient.pantryId`; pantry/shopping
 * items reference it via `ingredientId`). `baseIngredient` groups genuine
 * subtypes together (e.g. "chicken-thigh" and "chicken-breast" both base
 * to "chicken") so "I have chicken" reasonably covers "recipe needs
 * chicken thighs" — without conflating unrelated ingredients that merely
 * share a word ("chicken" vs "chicken stock", "coconut" vs "coconut
 * milk"). `synonyms` drives free-text resolution — matching what a user
 * types in Pantry/Shopping against this registry — sorted longest-phrase-
 * first at lookup time so multi-word synonyms are tried before their
 * component words (see `resolveSynonym` in ingredientNormalize.ts).
 */
export interface IngredientEntity {
  id: string;
  canonicalName: string;
  /** Groups subtypes under one umbrella concept. Equal to `canonicalName` for a base/generic ingredient itself. */
  baseIngredient: string;
  displayName: string;
  category: PantryCategory;
  synonyms: string[];
}

